#!/usr/bin/env python3
"""Generate the LuaJIT-facing ImGui bindings from the vendored cimgui.

Inputs (crates/tempest-scripting/native/cimgui/):
  cimgui.h                       preprocessed with CIMGUI_DEFINE_ENUMS_AND_STRUCTS -> the ffi.cdef text
  generator/structs_and_enums.json  enum values (pre-computed by cimgui's generator)
  generator/definitions.json        argument names/types for the LuaLS stubs

Outputs (all committed; rerun after updating cimgui):
  crates/tempest-scripting/src/imgui_cdef.lua   Lua chunk: { cdef = [=[...]=], enums = {...}, fns = {...} }
  crates/tempest-scripting/src/imgui_syms.rs    extern "C" declarations + name -> address table
  types/imgui.d.lua                             LuaLS stubs for ui.C.* (the raw cimgui API)

Needs a C preprocessor: x86_64-w64-mingw32-gcc (preferred, the target's
toolchain) or cc. The stubs in native/cdef-stubs/ replace the standard
headers so the output only contains cimgui's own declarations.
"""
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CRATE = os.path.join(ROOT, "crates", "tempest-scripting")
NATIVE = os.path.join(CRATE, "native")
CIMGUI = os.path.join(NATIVE, "cimgui")


def preprocess() -> str:
    cc = shutil.which("x86_64-w64-mingw32-gcc") or shutil.which("cc")
    if not cc:
        sys.exit("need x86_64-w64-mingw32-gcc or cc on PATH")
    cmd = [
        cc, "-E", "-P", "-x", "c", "-nostdinc",
        "-I", os.path.join(NATIVE, "cdef-stubs"),
        "-DCIMGUI_DEFINE_ENUMS_AND_STRUCTS", "-DCIMGUI_NO_EXPORT",
        os.path.join(CIMGUI, "cimgui.h"),
    ]
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


PROTO = re.compile(r"^extern\s+(.*?)\s*\b(\w+)\((.*)\);\s*$")


def build_cdef(pre: str):
    """Turn prototypes into function-pointer typedefs; return (cdef, names)."""
    out, names = [], []
    for line in pre.splitlines():
        line = line.rstrip()
        if not line:
            continue
        m = PROTO.match(line)
        if m:
            ret, name, args = m.groups()
            out.append(f"typedef {ret} (*tempest_fn_{name})({args});")
            names.append(name)
            continue
        if line.startswith("extern"):
            continue  # extern variables (GImGui): not reachable through addresses we hand out
        out.append(line)
    text = "\n".join(out) + "\n"
    if "]=]" in text:
        sys.exit("cdef text contains ']=]'")
    return text, names


def enum_group(enum_name: str) -> str:
    g = enum_name.rstrip("_")
    for prefix in ("ImGui", "Im"):
        if g.startswith(prefix):
            return g[len(prefix):]
    return g


def entry_name(enum_name: str, name: str) -> str:
    base = enum_name.rstrip("_") + "_"
    if name.startswith(base):
        return name[len(base):]
    for prefix in ("ImGui", "Im"):
        if name.startswith(prefix):
            return name[len(prefix):]
    return name


def lua_key(k: str) -> str:
    return k if re.match(r"^[A-Za-z_]\w*$", k) else f'["{k}"]'


def build_enums(se) -> str:
    lines = []
    for enum_name in sorted(se["enums"]):
        group = enum_group(enum_name)
        lines.append(f"\t{lua_key(group)} = {{")
        for e in se["enums"][enum_name]:
            lines.append(f"\t\t{lua_key(entry_name(enum_name, e['name']))} = {e['calc_value']},")
        lines.append("\t},")
    return "\n".join(lines)


def write_lua(cdef: str, names, se):
    path = os.path.join(CRATE, "src", "imgui_cdef.lua")
    fns = "\n".join(f'\t"{n}",' for n in names)
    with open(path, "w", newline="\n") as fh:
        fh.write("-- Generated by scripts/gen_imgui.py from native/cimgui (cimgui 1.91.9). Do not edit.\n")
        fh.write("-- cdef: cimgui.h with CIMGUI_DEFINE_ENUMS_AND_STRUCTS; every function is a\n")
        fh.write("-- `tempest_fn_<name>` pointer typedef, bound by address in ui.lua.\n")
        fh.write("return {\n")
        fh.write("cdef = [=[\n")
        fh.write(cdef)
        fh.write("]=],\n")
        fh.write("fns = {\n")
        fh.write(fns)
        fh.write("\n},\n")
        fh.write("enums = {\n")
        fh.write(build_enums(se))
        fh.write("\n},\n")
        fh.write("}\n")
    return path


def write_rust(names):
    path = os.path.join(CRATE, "src", "imgui_syms.rs")
    with open(path, "w", newline="\n") as fh:
        fh.write("// Generated by scripts/gen_imgui.py from native/cimgui (cimgui 1.91.9). Do not edit.\n")
        fh.write("//! Addresses of every cimgui function, handed to Lua so `ui.C.<name>` can\n")
        fh.write("//! `ffi.cast` them (no DLL export table involved). The signatures here are\n")
        fh.write("//! deliberately empty: only the addresses are taken, never called from Rust.\n\n")
        fh.write("#[allow(improper_ctypes, non_snake_case)]\n")
        fh.write('extern "C" {\n')
        for n in names:
            fh.write(f"    fn {n}();\n")
        fh.write("}\n\n")
        fh.write("/// `(name, address)` for every cimgui function.\n")
        fh.write("pub fn table() -> Vec<(&'static str, usize)> {\n")
        fh.write("    vec![\n")
        for n in names:
            fh.write(f'        ("{n}", {n} as *const () as usize),\n')
        fh.write("    ]\n}\n")
    return path


def luals_type(c: str, enums) -> str:
    c = c.strip()
    if c == "...":
        return "..."
    if c in ("void",):
        return "nil"
    if c == "bool":
        return "boolean"
    if c in ("const char*", "char*"):
        return "string"
    if c.endswith("*") or c.endswith("]") or "(*)" in c:
        return "ffi.cdata*"
    if c in ("float", "double"):
        return "number"
    if c in enums or c.startswith("ImGui") and c[5:6].isupper() and c in ("ImGuiID",):
        return "integer"
    if re.match(r"^(unsigned |signed |const )*(int|short|long|char|size_t|ImU\d+|ImS\d+|ImWchar\w*|ImGuiID|ImTextureID|ImGuiKeyChord|ImDrawIdx|ImGui\w*Flags|ImGui\w*)$", c) and c not in ("ImVec2", "ImVec4", "ImColor", "ImRect"):
        return "integer"
    return c


def write_luals(defs, se):
    enum_types = set(enum_group("x") and n.rstrip("_") for n in se["enums"])
    path = os.path.join(ROOT, "types", "imgui.d.lua")
    with open(path, "w", newline="\n") as fh:
        fh.write("---@meta\n")
        fh.write("-- Generated by scripts/gen_imgui.py: the raw cimgui API reachable as ui.C.<name>.\n")
        fh.write("-- Structs are LuaJIT cdata (ffi.new(\"ImVec2\", x, y)); enums live in ui.<Group>.<Name>.\n\n")
        for st in ("ImVec2", "ImVec4", "ImColor", "ImRect", "ImDrawList", "ImGuiIO", "ImGuiStyle", "ImFont", "ImGuiViewport", "ImGuiErrorRecoveryState"):
            fh.write(f"---@class {st}: ffi.cdata*\n")
        fh.write("\n---@class imgui.C\n")
        for name in sorted(defs):
            for ov in defs[name]:
                fname = ov["ov_cimguiname"]
                if any("va_list" in a["type"] for a in ov.get("argsT", [])):
                    continue
                params = []
                for a in ov.get("argsT", []):
                    t = luals_type(a["type"], enum_types)
                    if t == "...":
                        params.append("...")
                    else:
                        params.append(f"{lua_param(a['name'])}: {t}")
                ret = luals_type(ov.get("ret", "void"), enum_types)
                sig = f"fun({', '.join(params)})" + ("" if ret == "nil" else f": {ret}")
                fh.write(f"---@field {fname} {sig}\n")
        fh.write("local C = {}\n")
    return path


def lua_param(n: str) -> str:
    n = n.replace("[]", "")
    return n + "_" if n in ("end", "repeat", "function", "local", "in", "not", "or", "and", "nil", "true", "false", "then", "else", "elseif", "if", "while", "do", "for", "return", "break", "until", "goto") else n


def main():
    se = json.load(open(os.path.join(CIMGUI, "generator", "structs_and_enums.json")))
    defs = json.load(open(os.path.join(CIMGUI, "generator", "definitions.json")))
    pre = preprocess()
    cdef, names = build_cdef(pre)
    print("wrote", write_lua(cdef, names, se), f"({len(names)} functions, {len(se['enums'])} enums)")
    print("wrote", write_rust(names))
    print("wrote", write_luals(defs, se))


if __name__ == "__main__":
    main()
